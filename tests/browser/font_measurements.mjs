import assert from 'node:assert/strict';
import {createFontMeasurements} from '../../platform/browser/font-measurements.js';
let calls=0;
const context={font:'',measureText(text){calls++;return {width:this.font.length+text.length,actualBoundingBoxAscent:12};}};
const metrics=createFontMeasurements(context,(surface,font)=>{surface.font=font.family;},2,5);
const first={family:'regular'},second={family:'bold'};
const original=metrics.measure(1,first,'ab');
assert.equal(metrics.measure(1,first,'ab'),original,'Repeated text must reuse its measured shape');
const other=metrics.measure(2,second,'ab');
assert.notEqual(other,original,'Fonts must retain independent measurements');
assert.equal(calls,2);
metrics.forget(1);
assert.equal(metrics.measure(2,second,'ab'),other,'Closing one font evicted another font');
assert.notEqual(metrics.measure(1,first,'ab'),original,'Closing a font retained its measurements');
metrics.measure(1,first,'cd');
const before=calls;
metrics.measure(2,second,'ab');
assert.equal(calls,before+1,'The entry budget did not evict the oldest measurement');
const cached=metrics.measure(1,first,'cd');
const oversized=metrics.measure(1,first,'a long line');
assert.equal(oversized.width,first.family.length+11);
assert.equal(metrics.measure(1,first,'cd'),cached,'An oversized line displaced bounded cached text');
const beforeLarge=calls;
metrics.measure(1,first,'a long line');
assert.equal(calls,beforeLarge+1,'The character budget retained an oversized key');
const small=createFontMeasurements(context,(surface,font)=>{surface.font=font.family;},8,3);
small.measure(1,first,'ab');small.measure(1,first,'cd');
const beforeCharacters=calls;
small.measure(1,first,'ab');
assert.equal(calls,beforeCharacters+1,'The character budget did not bound cached keys');
console.log('Font measurements reuse immutable metrics per font, bound entries and text, and release closed fonts.');
