import assert from 'node:assert/strict';

export async function verifyForms({click,key,evaluate,command,waitFor,settled,screenshot}) {
  const value=()=>evaluate('document.querySelector("textarea").value');
  const visible=text=>`window.uiTest.drawn().join(' ').includes(${JSON.stringify(text)})`;
  await click(280,60);
  await key('Tab','Tab',9);
  await waitFor('document.activeElement.tagName==="TEXTAREA"');
  assert.equal(await value(),'Ada');
  assert.equal(await evaluate('getComputedStyle(document.querySelector("textarea")).fontSize'),'18px');
  await key('a','KeyA',65,2);
  await command('Input.insertText',{text:'Ada\nLovelace'});
  await waitFor('document.querySelector("textarea").value==="AdaLovelace"');
  await waitFor(visible('AdaLovelace'));
  await key('a','KeyA',65,2);
  await command('Input.imeSetComposition',{text:'とうきょう',selectionStart:5,selectionEnd:5});
  await waitFor('window.uiTest.drawn().some(text=>text.includes("とうきょう"))');
  assert(await evaluate(visible('AdaLovelace')),'Tentative field composition changed application state.');
  await screenshot('forms-composing');
  await command('Input.insertText',{text:'東京'});
  await waitFor('document.querySelector("textarea").value==="東京"');
  await key('z','KeyZ',90,2);
  await waitFor('document.querySelector("textarea").value==="AdaLovelace"');
  await key('z','KeyZ',90,10);
  await waitFor('document.querySelector("textarea").value==="東京"');
  await key('a','KeyA',65,2);
  await command('Input.insertText',{text:'Zoë'});
  await waitFor(visible('Zoë'));
  await key('Tab','Tab',9);
  await key(' ','Space',32);
  await waitFor(visible('Auto save on'));
  await key('Tab','Tab',9);
  await key('Enter','Enter',13);
  await waitFor('window.uiTest.drawn().includes("Code review")');
  await screenshot('forms-choices');
  await key('End','End',35);
  await waitFor('window.uiTest.drawn().includes("Resting") && !window.uiTest.drawn().includes("Code review")');
  await screenshot('forms-choices-end');
  await key('Home','Home',36);
  await key('ArrowDown','ArrowDown',40);
  await key('Enter','Enter',13);
  await waitFor(`${visible('Calm')} && !window.uiTest.drawn().includes('Code review')`);
  await screenshot('forms-edited');
  await key('Enter','Enter',13);
  await waitFor('window.uiTest.drawn().includes("Code review")');
  await key('Escape','Escape',27);
  await waitFor('!window.uiTest.drawn().includes("Code review")');
  await key('Tab','Tab',9,8);
  await key('Tab','Tab',9,8);
  await waitFor('document.activeElement.tagName==="TEXTAREA"');
  await command('Emulation.setDeviceMetricsOverride',{width:375,height:820,deviceScaleFactor:2,mobile:false});
  await settled();
  const long='é🙂'.repeat(100);
  await key('a','KeyA',65,2);
  await command('Input.insertText',{text:long});
  await waitFor(`document.querySelector('textarea').value===${JSON.stringify(long)}`);
  const caret=await evaluate(`(() => {
    const input=document.querySelector('textarea'), box=input.getBoundingClientRect();
    return {x:box.x,right:box.right,font:getComputedStyle(input).fontSize};
  })()`);
  assert(caret.x>=0 && caret.right<=375 && caret.font==='18px',
    `The scrolled field lost its input geometry: ${JSON.stringify(caret)}`);
  await screenshot('forms-mobile-long');
  await key('a','KeyA',65,2);
  await command('Input.insertText',{text:'Zoë'});
  await waitFor('document.querySelector("textarea").value==="Zoë"');
  await key('Tab','Tab',9);
  await key('Tab','Tab',9);
  await key('Tab','Tab',9);
  await key('Enter','Enter',13);
  await waitFor(visible('Ada · Focused · Auto save off'));
  await screenshot('forms-mobile-reset');
}
